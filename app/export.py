"""Markdown export for MANUAL handoff to NotebookLM or any notes tool.

This is a one-time snapshot, not live synchronization: nothing is sent anywhere and
NotebookLM is never contacted.
"""
from __future__ import annotations

from datetime import datetime, timezone

from .config import DEMO_LABEL
from .conversations import get_conversation

HANDOFF = (
    "> **Manual handoff, not synchronization.** This file is a snapshot you can paste or "
    "upload into NotebookLM or another notes tool yourself. The app does not connect to "
    "NotebookLM and nothing here updates automatically. These are *your study notes* "
    "(secondary material): keep them separate from your primary sources, and re-check "
    "quotations against the original documents.")


def _excerpt(text: str, n: int = 500) -> str:
    t = " ".join((text or "").split())
    return t if len(t) <= n else t[: n - 1] + "…"


def _doc_line(conn, doc_id, fallback_title):
    row = conn.execute("SELECT * FROM documents WHERE id=?", (doc_id,)).fetchone()
    if not row:
        return f"**{fallback_title}** (document no longer in the library)"
    bits = [f"**{row['title']}**"]
    if row["author"]:
        bits.append(f"by {row['author']}")
    meta = [x for x in (row["date"], row["edition"]) if x]
    if meta:
        bits.append("(" + "; ".join(meta) + ")")
    bits.append(f"— file `{row['original_filename']}`")
    if row["kind"] == "secondary_notes":
        bits.append("— *secondary study notes, not a primary source*")
    return " ".join(bits)


def export_markdown(conn, cid: str, include_transcript: bool = False) -> str:
    conv = get_conversation(conn, cid)
    ex = conv.get("exercise")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [f"# {conv['title']}", "", f"_Exported {now}_", "", HANDOFF, ""]

    labels = {m["provider_label"] for m in conv["messages"] if m.get("provider_label") and m["provider_label"] != "App"}
    out += ["## Session", f"- Type: {'exercise' if conv['mode'] == 'exercise' else 'chat'}",
            f"- Source scope: {_scope_text(conn, conv['scope'])}",
            f"- Created: {conv['created_at']}; last updated: {conv['updated_at']}"]
    if ex:
        out.append(f"- Exercise: {ex['mode']} · {ex['level']} · {ex['scenario_kind']} scenario"
                   f" · hints used: {ex['hints_used']} · attempts: {len(ex['attempts'])}")
    for lab in sorted(labels):
        out.append(f"- Generated by: {lab}")
    if any(lab.startswith("Demo") for lab in labels):
        out += ["", f"> ⚠ **{DEMO_LABEL}** Demo content illustrates the interaction only."]
    out.append("")

    if ex:
        out += ["## Reflection"]
        if ex.get("reflection"):
            for b in ex["reflection"]:
                out += [b["text"], ""]
        else:
            out += ["_No end-of-session reflection yet (finish the exercise to generate one)._", ""]
        if ex.get("attempts"):
            out += ["## Your attempts (your own words)"]
            for a in ex["attempts"]:
                out += [f"**Attempt {a['n']}** ({a['phase']}):", "", "> " + a["text"].replace("\n", "\n> "), ""]
        out += ["_Rubric note: the exercise rubric is an app-created learning aid, not a canonical standard._", ""]
    else:
        out += ["## Reflection", "_Chat sessions have no automatic reflection. Add your own notes here._", ""]

    # source references (validated citations only), grouped by document
    refs: dict[str, dict] = {}
    for m in conv["messages"]:
        if m["role"] != "assistant" or not m.get("blocks"):
            continue
        snaps = {e["id"]: e for e in (m.get("evidence") or [])}
        for b in m["blocks"]:
            for c in b.get("citations") or []:
                if not c.get("ok"):
                    continue
                s = snaps.get(c["passage_id"])
                d = refs.setdefault(c["doc_id"], {"title": c.get("doc_title") or "", "passages": {}})
                d["passages"].setdefault(c["passage_id"], {
                    "location": c.get("location"), "text": s["text"] if s else ""})
    out += ["## Source references",
            "_Citations listed here passed the app's mechanical checks (passage supplied, document "
            "approved and in scope, quotation present). That does not prove a passage supports a "
            "particular interpretation._", ""]
    if not refs:
        out += ["_No validated citations in this session._", ""]
    for doc_id, d in refs.items():
        out += [f"### {_doc_line(conn, doc_id, d['title'])}", ""]
        for pid, p in d["passages"].items():
            out += [f"- `{pid}` — {p['location']}", f"  > {_excerpt(p['text'])}"]
        out.append("")

    flagged = [(m, f) for m in conv["messages"] for f in m.get("flags", [])]
    out += ["## Flagged for review (possible unsupported interpretations)"]
    if not flagged:
        out += ["_None flagged._", ""]
    for m, f in flagged:
        blk = (m.get("blocks") or [])
        idx = f.get("block_index")
        txt = _excerpt(blk[idx]["text"], 300) if isinstance(idx, int) and 0 <= idx < len(blk) else ""
        out += [f"- {('“' + txt + '” ') if txt else ''}— passage `{f.get('chunk_id') or 'n/a'}` — note: {f.get('note') or '(none)'}"]
    out.append("")

    if include_transcript:
        out += ["## Transcript"]
        for m in conv["messages"]:
            who = "You" if m["role"] == "user" else "Tutor"
            if m["role"] == "user":
                out += [f"**{who}:** {m['text']}", ""]
            else:
                out.append(f"**{who}** ({m.get('provider_label') or ''}):")
                for b in m.get("blocks") or []:
                    if b["type"] == "withheld":
                        out.append("- *(statement withheld: citation could not be verified)*")
                    else:
                        out.append(f"- *{b['type']}*: {b['text']}")
                out.append("")
    return "\n".join(out).rstrip() + "\n"


def _scope_text(conn, scope: dict) -> str:
    from .retrieval import Scope, describe_scope
    return describe_scope(conn, Scope.from_dict(scope))
